    def test_arquivo_que_o_comando_grava(self):
        # o msg do disco é velho; vale o que o comando grava antes do commit
        Path(self.dir.name, "msg").write_text("fix: antigo.\n", encoding="utf-8")
        bom = f"M=msg && cat > $M <<'EOF'\n{BOA}EOF\ngit commit -F $M"
        self.assertIsNone(self.conferir(bom))
        self.assertIsNone(self.conferir(f"cat <<'EOF' > msg\n{BOA}EOF\ngit commit -F msg"))
        self.assertIsNone(self.conferir(f"tee msg <<'EOF'\n{BOA}EOF\ngit commit -F ./msg"))
        Path(self.dir.name, "msg").write_text(BOA, encoding="utf-8")
        ruim = "cat > msg <<'EOF'\nfix: novo.\nEOF\ngit commit -F msg"
        self.assertIn("prefixo", self.conferir(ruim))
        # mostrar a mensagem antes do commit não muda o que ele lê
        for mostra in ["cat msg", "tail -5 msg", "wc -L msg", "git add msg"]:
            with self.subTest(mostra=mostra):
                cmd = f"cat > msg <<'EOF'\nfix: novo.\nEOF\n{mostra} && git commit -F msg"
                self.assertIn("prefixo", self.conferir(cmd))
        # gravado de outro jeito, ou acrescentado: não se sabe o que fica
        for cmd in ["printf 'fix: x' > msg && git commit -F msg",
                    "cat >> msg <<'EOF'\nmais\nEOF\ngit commit -F msg",
                    "cp outro msg && git commit -F msg",
                    "git log -1 --format=%B HEAD > msg; git commit -F msg"]:
            with self.subTest(cmd=cmd):
                Path(self.dir.name, "msg").write_text("fix: antigo.\n", encoding="utf-8")
                self.assertIsNone(self.conferir(cmd))

