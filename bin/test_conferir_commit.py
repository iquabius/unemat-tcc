SCRIPT = Path(os.environ.get("CONFERIR_COMMIT_SCRIPT",
                            Path(__file__).with_name("conferir-commit.py")))
spec = importlib.util.spec_from_file_location("conferir_commit", SCRIPT)
cc = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cc)

BOA = """\
Corrige a contagem de linhas do relatório

O relatório soma duas vezes a linha de total, e o número final sai
dobrado. A soma passa a ignorar a linha marcada como total; filtrar na
leitura esconderia a linha também da tela.

Conferido com o relatório de 2026-10-01, que passa de 84 para 42.

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>
"""


# O git dos repositórios de teste: sem a configuração global, e com ela os
# hooks da máquina; com nome e datas fixos, para o sha sair sempre o mesmo.
# Com a data do relógio, cerca de 4% dos shas curtos saem só com dígitos ou
# só com letras, e o SHA_CITADO não os lê como sha.
GIT_DE_TESTE = {"GIT_CONFIG_GLOBAL": "/dev/null", "GIT_CONFIG_NOSYSTEM": "1",
                "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t",
                "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@t",
                "GIT_AUTHOR_DATE": "2026-10-01T10:01:00-0400",
                "GIT_COMMITTER_DATE": "2026-10-01T10:01:00-0400"}


def skill(nome="commit-message"):
    return {"type": "assistant", "message": {"content": [
        {"type": "tool_use", "name": "Skill", "input": {"skill": nome}}]}}


class Base(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()
        self.addCleanup(self.dir.cleanup)
        # o diretório temporário faz as vezes do repositório do TCC
        subprocess.run(["git", "init", "-q", self.dir.name], check=True)
        repositorio = cc.REPOSITORIO
        cc.REPOSITORIO = Path(self.dir.name)
        self.addCleanup(setattr, cc, "REPOSITORIO", repositorio)
        # sem o diretório da sessão que o Claude Code põe no ambiente
        ambiente = unittest.mock.patch.dict(os.environ)
        ambiente.start()
        self.addCleanup(ambiente.stop)
        os.environ.pop("CLAUDE_PROJECT_DIR", None)
        self.transcript([skill()])

    def transcript(self, entradas, nome="sessao.jsonl"):
        p = Path(self.dir.name, nome)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text("".join(json.dumps(e) + "\n" for e in entradas), encoding="utf-8")
        self.caminho = Path(self.dir.name, "sessao.jsonl")
        return p

    def conferir(self, cmd, **extra):
        dados = {"tool_name": "Bash", "tool_input": {"command": cmd},
                 "transcript_path": str(self.caminho), "cwd": self.dir.name, **extra}
        return cc.conferir(dados)


