class Repositorio(Base):
    def test_outro_repositorio_passa(self):
        with tempfile.TemporaryDirectory() as outro:
            subprocess.run(["git", "init", "-q", outro], check=True)
            self.assertIsNone(self.conferir(f"cd {outro} && git commit -m 'fix: x'"))
            self.assertIsNone(self.conferir(f"git -C {outro} commit -m 'fix: x'"))
        self.assertIsNone(self.conferir("cd /tmp && git commit -m 'fix: x'"))

    def test_atribuicao_antes_de_comando_vale_so_para_ele(self):
        self.assertIn("prefixo", self.conferir("GIT_DIR=.git git status; git commit -m 'fix: x'"))
        self.assertIsNone(self.conferir("export GIT_DIR=/tmp/x/.git; git commit -m 'fix: x'"))

    def test_git_dir_aponta_outro_repositorio(self):
        for cmd in ["GIT_DIR=/tmp/outro/.git git commit -m 'fix: x'",
                    "git --git-dir=/tmp/x/.git commit -m 'fix: x'",
                    "git --work-tree /tmp/x commit -m 'fix: x'"]:
            with self.subTest(cmd=cmd):
                self.assertIsNone(self.conferir(cmd))

    def test_opcoes_do_env_e_do_git_que_levam_argumento(self):
        for cmd in ["env --unset HOME git commit -m 'fix: x'",
                    "env -u HOME git commit -m 'fix: x'",
                    "git --exec-path=/usr/lib/git-core commit -m 'fix: x'"]:
            with self.subTest(cmd=cmd):
                self.assertIn("prefixo", self.conferir(cmd))

    def test_env_C_muda_o_diretorio_do_comando(self):
        with tempfile.TemporaryDirectory() as outro:
            subprocess.run(["git", "init", "-q", outro], check=True)
            self.assertIsNone(self.conferir(f"env -C {outro} git commit -m 'fix: x'"))
            self.assertIsNone(self.conferir(f"env --chdir={outro} git commit -m 'fix: x'"))
            # o diretório do env vale só para o comando dele
            self.assertIn("prefixo", self.conferir(
                f"env -C {outro} true; git commit -m 'fix: x'"))

    def test_diretorio_desconhecido_passa(self):
        self.assertIsNone(self.conferir("cd \"$(mktemp -d)\" && git init -q && git commit -m x"))

    def test_worktree_e_subdiretorio_conferem(self):
        d = self.dir.name
        subprocess.run(["git", "-C", d, "commit", "-q", "--allow-empty", "-m", "x"],
                       check=True, env={**os.environ, "GIT_AUTHOR_NAME": "a",
                                        "GIT_AUTHOR_EMAIL": "a@a", "GIT_COMMITTER_NAME": "a",
                                        "GIT_COMMITTER_EMAIL": "a@a"})
        subprocess.run(["git", "-C", d, "worktree", "add", "-q", "wt"], check=True)
        Path(d, "sub").mkdir()
        self.assertIn("prefixo", self.conferir("cd wt && git commit -m 'fix: x'"))
        self.assertIn("prefixo", self.conferir("cd sub && git commit -m 'fix: x'"))


