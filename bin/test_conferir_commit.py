#!/usr/bin/env python3
"""Testes do bin/conferir-commit.py, sem Claude Code; cada teste cria um
repositório git num diretório temporário, que faz as vezes do do TCC:

    python3 -m unittest discover -s bin -p 'test_*.py'
"""
import importlib.util
