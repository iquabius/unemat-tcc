    def test_fixup_so_fora_do_ramo_principal(self):
        for principal in ["master", "main"]:
            with self.subTest(ramo=principal):
                subprocess.run(["git", "-C", self.dir.name, "symbolic-ref", "HEAD",
                                f"refs/heads/{principal}"], check=True)
                self.assertIn("--fixup", self.conferir("git commit --fixup=abc123"))
                self.assertIn("--fixup", self.conferir("git commit --squash=abc123"))
        subprocess.run(["git", "-C", self.dir.name, "symbolic-ref", "HEAD",
                        "refs/heads/tarefa"], check=True)
        self.assertIsNone(self.conferir("git commit --fixup=abc123"))
        self.assertIsNone(self.conferir("git commit --squash=abc123"))

    def test_fixup_com_head_destacado(self):
        d = self.dir.name
        ambiente = {**os.environ, "GIT_AUTHOR_NAME": "a", "GIT_AUTHOR_EMAIL": "a@a",
                    "GIT_COMMITTER_NAME": "a", "GIT_COMMITTER_EMAIL": "a@a"}
        subprocess.run(["git", "-C", d, "symbolic-ref", "HEAD", "refs/heads/master"], check=True)
        for _ in range(2):
            subprocess.run(["git", "-C", d, "commit", "-q", "--allow-empty", "-m", "x"],
                           check=True, env=ambiente)
        # destacado na ponta do master, como a worktree em que o merge se monta
        subprocess.run(["git", "-C", d, "switch", "-q", "--detach", "master"], check=True)
        self.assertIn("--fixup", self.conferir("git commit --fixup=abc123"))
        # destacado noutro commit
        subprocess.run(["git", "-C", d, "switch", "-q", "--detach", "master~1"], check=True)
        self.assertIsNone(self.conferir("git commit --fixup=abc123"))

