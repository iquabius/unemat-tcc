class Saida(Base):
    def rodar(self, entrada):
        # o script roda contra o próprio repositório, de dentro dele
        return subprocess.run([sys.executable, str(SCRIPT)], input=entrada,
                              capture_output=True, text=True, cwd=SCRIPT.parent)

    def test_recusa_em_json(self):
        r = self.rodar(json.dumps({"tool_name": "Bash", "tool_input": {
            "command": "git commit -m 'fix: x'"}, "transcript_path": str(self.caminho)}))
        self.assertEqual(r.returncode, 0)
        saida = json.loads(r.stdout)["hookSpecificOutput"]
        self.assertEqual(saida["permissionDecision"], "deny")
        self.assertIn("prefixo", saida["permissionDecisionReason"])

    def test_campo_de_tipo_errado_nao_derruba(self):
        r = self.rodar(json.dumps({"tool_name": "Bash", "tool_input": {"command": "git commit -m x"},
                                   "cwd": 3, "transcript_path": ["x"], "agent_id": 7}))
        self.assertEqual((r.returncode, r.stderr), (0, ""))

    def test_entrada_ruim_sai_calada(self):
        for entrada in ["", "não é json", "[]",
                        json.dumps({"tool_name": "Bash", "tool_input": "git commit -m x"}),
                        json.dumps({"tool_name": "Bash", "tool_input": {"command": ["git", "commit"]}}),
                        json.dumps({"tool_name": "Bash", "tool_input": {"command": "git commit -m 'a"}})]:
            with self.subTest(entrada=entrada):
                r = self.rodar(entrada)
                self.assertEqual((r.returncode, r.stdout), (0, ""))


